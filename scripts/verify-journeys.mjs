#!/usr/bin/env node
// `S-3b` / `S-3c` (decisions 16 and 17): every browser statement is used by at least three journeys,
// and every workload shape by at least one, and CONSTRUCTS.md's `## Journeys` table says how many.
// The count and the floors are `scripts/lib/journeys.mjs`'s; this script holds the table to them.
//
//   node scripts/verify-journeys.mjs           — check (exit 1 on a floor missed or a stale table)
//   node scripts/verify-journeys.mjs --write   — rewrite the table from the count
//
// A floor is a ratchet in one direction only: a journey removed below it is a red here, and the
// fix is another journey, never a lower number. A table that disagrees with the tree is a red too,
// so a count that moves is a visible diff rather than a silent one.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { JOURNEY_STATEMENTS, countJourneys, testBodies } from './lib/journeys.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CATALOGUE = path.join(ROOT, 'CONSTRUCTS.md');
const START = '<!-- journeys:start — generated by `node scripts/verify-journeys.mjs --write`; never hand-edit -->';
const END = '<!-- journeys:end -->';

// The counter's own negative control: a test that clicks twice is one journey, a spike's `hold N
// for` stage is not a `hold`, and a line that only mentions a keyword in a comment counts for nothing.
{
  const fixture = [
    '@ui',
    'test "a"',
    '  click button "x"',
    '  click button "y"',
    '  # hover button "not a step"',
    'test "b"',
    '  spike rps',
    '    hold 2 for 1s',
    '    to 5 over 1s',
    'action helper()',
    '  hover button "in an action, not a test"',
  ].join('\n');
  const bodies = testBodies(fixture);
  const uses = (id) => bodies.filter((b) => b.some((l) => JOURNEY_STATEMENTS.find(([k]) => k === id)[1].test(l))).length;
  const got = { tests: bodies.length, click: uses('step:click'), hover: uses('step:hover'), hold: uses('step:hold'), spike: uses('step:spike') };
  const want = { tests: 2, click: 1, hover: 0, hold: 0, spike: 1 };
  if (JSON.stringify(got) !== JSON.stringify(want)) {
    console.error(`✗ the journey counter's own control disagrees: got ${JSON.stringify(got)}, want ${JSON.stringify(want)}`);
    process.exit(1);
  }
}

const counts = countJourneys(path.join(ROOT, 'tests'));
const table = [
  START,
  '| construct | lens | journeys | floor |',
  '|---|---|---|---|',
  ...JOURNEY_STATEMENTS.map(([id, , floor, lens]) => `| \`${id}\` | ${lens} | ${counts.get(id)} | ${floor} |`),
  END,
].join('\n');

const text = readFileSync(CATALOGUE, 'utf8');
const from = text.indexOf(START);
const to = text.indexOf(END);
if (from === -1 || to === -1) {
  console.error(`✗ CONSTRUCTS.md has no journeys table between its markers — write it: node scripts/verify-journeys.mjs --write`);
  if (!process.argv.includes('--write')) process.exit(1);
}

if (process.argv.includes('--write')) {
  if (from === -1 || to === -1) {
    console.error('✗ add the two marker lines under `## Journeys` first, then --write fills them');
    process.exit(1);
  }
  writeFileSync(CATALOGUE, text.slice(0, from) + table + text.slice(to + END.length));
  console.log(`✎ CONSTRUCTS.md's journeys table rewritten — ${JOURNEY_STATEMENTS.length} statements`);
  process.exit(0);
}

const problems = [];
for (const [id, , floor] of JOURNEY_STATEMENTS) {
  if (counts.get(id) < floor) problems.push(`${id} is used by ${counts.get(id)} journey(s); its floor is ${floor} — add a journey, never lower the floor`);
}
if (text.slice(from, to + END.length) !== table) {
  problems.push('CONSTRUCTS.md\'s journeys table is not the count this tree gives — node scripts/verify-journeys.mjs --write, and commit the diff');
}
if (problems.length > 0) {
  for (const p of problems) console.error(`✗ ${p}`);
  process.exit(1);
}
console.log(`✓ journeys: ${JOURNEY_STATEMENTS.length} statements, each at or above its floor; the table matches the tree`);
